#!/usr/bin/env bash
# Mullvad WireGuard tunnel on the server, and the server as a VPN gateway for the home.
# Run as root, after copying the Mullvad config from mullvad.net to ~/mullvad.conf:
#
#   sudo bash ~/nuvytrix/nuvytrix-backend/deploy/vpn/setup.sh
#
# What it does (docs/vpn.md):
#   1. /etc/wireguard/mullvad.conf from the downloaded file: key, IPv4 address and peer only. No
#      DNS change (AdGuard keeps its own encrypted upstreams), no routes in the main table: the
#      server's own traffic (sites' Cloudflare tunnels, Tailscale, updates) stays direct.
#   2. Forwarded traffic from the LAN is routed by table 51: through the tunnel while it works,
#      straight to the router when it does not (watchdog every 15 s, the owner chose "internet
#      always works" over a kill switch). LAN-to-LAN traffic is never touched.
#   3. NAT and TCP MSS clamping for forwarded traffic, ufw route rules, no ICMP redirects.
# Nothing changes for any device until it uses 192.168.100.27 as its gateway (AdGuard DHCP).
# The private key is never printed.
set -euo pipefail

SRC=${1:-/home/aleksa/mullvad.conf}
HERE=$(cd "$(dirname "$0")" && pwd)

[ "$(id -u)" = 0 ] || { echo "run with sudo"; exit 1; }
[ -f "$SRC" ] || { echo "ABORT: $SRC not found (download it from mullvad.net, Linux, WireGuard)"; exit 1; }

field() { sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*//p" "$SRC" | head -1 | tr -d '\r'; }
KEY=$(field PrivateKey)
ADDR=$(field Address | tr ',' '\n' | tr -d ' ' | grep -m1 '^[0-9.]*/[0-9]*$' || true)
PUB=$(field PublicKey)
ENDPOINT=$(field Endpoint)
for v in KEY ADDR PUB ENDPOINT; do
  [ -n "${!v}" ] || { echo "ABORT: $v missing in $SRC"; exit 1; }
done

umask 077
cat > /etc/wireguard/mullvad.conf <<EOF
# Generated by Nuvytrix deploy/vpn/setup.sh from the Mullvad config. Table = off: no routes in the
# main table; deploy/vpn/gateway.sh decides what goes through the tunnel.
[Interface]
PrivateKey = $KEY
Address = $ADDR
Table = off

[Peer]
PublicKey = $PUB
Endpoint = $ENDPOINT
AllowedIPs = 0.0.0.0/0
PersistentKeepalive = 25
EOF
umask 022

install -m 0755 "$HERE/gateway.sh" /usr/local/sbin/nuvytrix-vpn-gateway
cat > /etc/systemd/system/nuvytrix-vpn-gateway.service <<'EOF'
[Unit]
Description=Nuvytrix: home VPN gateway (routing, NAT) on top of the Mullvad tunnel
After=wg-quick@mullvad.service network-online.target ufw.service docker.service
Wants=wg-quick@mullvad.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/nuvytrix-vpn-gateway up
ExecStop=/usr/local/sbin/nuvytrix-vpn-gateway down

[Install]
WantedBy=multi-user.target
EOF
cat > /etc/systemd/system/nuvytrix-vpn-watchdog.service <<'EOF'
[Unit]
Description=Nuvytrix: route the home through Mullvad while the tunnel works, else directly

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/nuvytrix-vpn-gateway check
EOF
cat > /etc/systemd/system/nuvytrix-vpn-watchdog.timer <<'EOF'
[Unit]
Description=Nuvytrix VPN watchdog every 15 seconds

[Timer]
OnBootSec=30s
OnUnitActiveSec=15s
AccuracySec=1s

[Install]
WantedBy=timers.target
EOF

cat > /etc/sysctl.d/60-nuvytrix-gateway.conf <<'EOF'
# The server forwards the home's traffic (deploy/vpn). No ICMP redirects: they would tell devices
# to skip the server and use the router directly.
net.ipv4.ip_forward = 1
net.ipv4.conf.all.send_redirects = 0
net.ipv4.conf.enp4s0.send_redirects = 0
EOF
sysctl -q -p /etc/sysctl.d/60-nuvytrix-gateway.conf

ufw route allow in on enp4s0 out on mullvad from 192.168.100.0/24 comment 'Home through Mullvad' >/dev/null
ufw route allow in on enp4s0 out on enp4s0 from 192.168.100.0/24 comment 'Home direct (tunnel down)' >/dev/null

systemctl daemon-reload
systemctl enable --now wg-quick@mullvad
systemctl enable --now nuvytrix-vpn-gateway.service
systemctl enable --now nuvytrix-vpn-watchdog.timer
sleep 5
/usr/local/sbin/nuvytrix-vpn-gateway check

echo
echo "Tunnel check (the server's own traffic still goes direct; this asks through the tunnel):"
curl -s --max-time 10 --interface "${ADDR%/*}" https://am.i.mullvad.net/connected || echo "no answer through the tunnel"
echo
echo "ok: tunnel and gateway ready. No device uses it yet (gateway in AdGuard DHCP is still the router)."
